def main() -> int:
    log = Logger()
    git = git_info()
    log("T122 cables+trays runner start")
    log(f"  branch={git['branch']}  commit={git['short']}")
    log(f"  PDF_DIR={PDF_DIR}")

    if not PDF_DIR.is_dir():
        log("FATAL: PDF_DIR missing")
        return 2
    pdfs = sorted(PDF_DIR.glob("*.pdf"))
    log(f"  found {len(pdfs)} PDFs")

    # --- Cables ---
    cables_per_file, cables_rows = run_cables(pdfs, log)
    write_cables_xlsx(cables_rows, CABLES_XLSX)
    log(f"WROTE {CABLES_XLSX.name}  rows={len(cables_rows)}  "
        f"total_m={sum(r['total_m'] for r in cables_rows):.1f}")

    # --- Trays ---
    trays_per_file, trays_rows = run_trays(pdfs, log)
    added = _augment_with_counts(trays_rows, log)
    log(f"  added qty from equipment_report.json: {added}")
    write_trays_xlsx(trays_rows, TRAYS_XLSX)
    log(f"WROTE {TRAYS_XLSX.name}  rows={len(trays_rows)}  "
        f"sum_qty={sum(r['total_qty'] for r in trays_rows)}")

    write_discussion(log.lines, cables_per_file, cables_rows,
                     trays_per_file, trays_rows, git)
    log(f"WROTE {T122_MD}")
    log("T122 cables+trays runner done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
