def _norm_method(m: str) -> str:
    return METHOD_LABEL.get(m, m)


def _format_section(sec: str | None) -> str:
    if not sec:
        return ""
    return sec.replace("x", "x")  # already canonical from pdf_cables_by_method


def run_cables(pdfs: list[Path], log: Logger) -> tuple[list[dict], list[dict]]:
    """Run measure_cables on lighting-plan sheets. Returns:
       (per_file_summary, aggregated_rows)
    aggregated_rows are dicts ready for XLSX:
       {cable_mark, cable_color, laying_method, cross_section, unit, total_m}
    """
    per_file: list[dict] = []
    # Aggregation key: (mark, color, method, section)
    bucket: dict[tuple, float] = defaultdict(float)
    # Track which sheets used which marks for the report.
    sheet_marks_log: list[tuple[str, list]] = []

    for pdf in pdfs:
        if not CABLE_SHEET_RE.match(pdf.name):
            continue
        log(f"  cables: {pdf.name}")
        t0 = time.time()
        try:
            rep = measure_cables(str(pdf))
        except Exception as exc:
            log(f"    ERROR: {type(exc).__name__}: {exc}")
            log("    " + traceback.format_exc().replace("\n", "\n    "))
            per_file.append(dict(pdf=pdf.name, error=str(exc),
                                  totals_m={}, mark="", section=""))
            continue

        # Pick the dominant cable mark from sheet text. Fall back to "".
        marks = rep.sheet_cable_marks or []
        sheet_marks_log.append((pdf.name, [
            dict(mark=m["mark"], section=m["section"], mentions=m["mentions"])
            for m in marks[:3]
        ]))
        primary = marks[0] if marks else None
        primary_mark = (primary["mark"].upper() if primary else "")
        primary_section = (primary["section"] or "" if primary else "")

        # Aggregate totals_m per (color, method) for THIS sheet
        sheet_total = 0.0
        for (color, method), L in rep.totals_m.items():
            canonical = _norm_method(method)
            key = (primary_mark, color, canonical, primary_section)
            bucket[key] += L
            sheet_total += L

        per_file.append(dict(
            pdf=pdf.name,
            elapsed_s=round(time.time() - t0, 2),
            scale_mm_per_pt=rep.scale_mm_per_pt,
            scale_source=rep.scale_source,
            sheet_default_method=rep.sheet_default_method,
            sheet_mark=primary_mark,
            sheet_section=primary_section,
            totals_m={f"{c}/{_norm_method(m)}": round(L, 1)
                      for (c, m), L in rep.totals_m.items()},
            cable_total_m=round(sheet_total, 1),
            label_total_m=round(rep.label_total_m, 1),
            polylines=len(rep.polylines),
            raw_red=rep.raw_red_lines,
            raw_blue=rep.raw_blue_lines,
        ))
        log(f"    total_m={sheet_total:.1f}  mark={primary_mark or '?'}  "
            f"section={primary_section or '?'}  pl={len(rep.polylines)}")

    rows: list[dict] = []
    for (mark, color, method, section), total_m in bucket.items():
        rows.append(dict(
            cable_mark=mark or "",
            cable_color=color,
            laying_method=method,
            cross_section=section or "",
            unit="м",
            total_m=round(total_m, 1),
        ))
    # Sort by mark, color, method, section for determinism.
    rows.sort(key=lambda r: (r["cable_mark"], r["cable_color"],
                              r["laying_method"], r["cross_section"]))
    return per_file, rows


