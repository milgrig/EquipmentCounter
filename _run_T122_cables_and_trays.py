def _is_tray_name(name: str) -> bool:
    n = (name or "").lower()
    if not n or n.startswith("[auto-detected") or n.startswith("[equipment"):
        return False
    if any(k in n for k in TRAY_KEYWORDS):
        return True
    if any(k in n for k in TRAY_ACCESSORY_KEYWORDS):
        return True
    return False


def _normalize_tray_name(name: str) -> str:
    """Strip elevation tokens and noise tail; mirrors run_T122_gpk3_count_only
    normalize_name but tighter (we don't strip leading drawing numbers,
    legend descriptions don't carry those)."""
    s = name or ""
    s = re.sub(r"\s*на\s*отм\.?\s*[+-]?\d+[.,]\d+\s*", " ", s, flags=re.IGNORECASE)
    s = re.sub(r"\s*отм\.?\s*[+-]?\d+[.,]\d+\s*", " ", s, flags=re.IGNORECASE)
    s = re.sub(r"\s+", " ", s).strip(" ,.-—–")
    return s


def run_trays(pdfs: list[Path], log: Logger) -> tuple[list[dict], list[dict]]:
    """Parse legends of Лотки* sheets directly via pdf_legend_parser.

    For each tray sheet we walk the parsed legend rows. A legend row counts
    as a tray product if its description matches TRAY_* keywords. We
    accumulate per (normalized_name, unit) where unit comes from the sheet
    (м for lengths, шт for fittings — both inferred from name).
    """
    per_file: list[dict] = []
    bucket: "OrderedDict[tuple[str, str], dict]" = OrderedDict()

    for pdf in pdfs:
        if not TRAY_SHEET_RE.match(pdf.name):
            continue
        log(f"  trays: {pdf.name}")
        t0 = time.time()
        try:
            legend = parse_legend(str(pdf))
        except Exception as exc:
            log(f"    ERROR: {type(exc).__name__}: {exc}")
            per_file.append(dict(pdf=pdf.name, error=str(exc), n_items=0))
            continue

        items = legend.items if legend else []
        n_tray = 0
        for li in items:
            desc = li.description or ""
            if not _is_tray_name(desc):
                continue
            n_tray += 1
            norm = _normalize_tray_name(desc)
            # Heuristic: unit = м for "Лоток" alone, шт for fittings.
            low = norm.lower()
            if low.startswith("лоток") and "пластин" not in low and \
               "угол" not in low and "ответвитель" not in low and \
               "подвес" not in low and "консоль" not in low and \
               "скоба" not in low and "профиль" not in low and \
               "прижим" not in low and "поворот" not in low and \
               "планка" not in low and "кронштейн" not in low:
                unit = "м"
            else:
                unit = "шт"
            key = (norm.lower(), unit)
            b = bucket.setdefault(key, dict(
                item_name_normalized=norm,
                original_names=[],
                original_names_set=set(),
                unit=unit,
                total_qty=0,
                sheets=[],
            ))
            if desc not in b["original_names_set"]:
                b["original_names_set"].add(desc)
                b["original_names"].append(desc)
            # KB-015: legend items with empty symbol → silently dropped by the
            # downstream symbol counter. We can still record the legend row
            # itself (mention=1). For trays the symbol is rarely the actual
            # quantity; without DXF / explicit symbol matching we can only
            # report a presence count. We record 1 per sheet occurrence.
            if not li.symbol:
                # KB-015: empty symbol → no count emitted by equipment counter;
                # we tag mention but qty remains 0 to flag for manual review.
                inc = 0
            else:
                # Without a real symbol-counter call we cannot derive count
                # here. We attempt to read counts from equipment_report.json
                # for the same symbol on the same PDF (if present), see
                # _augment_with_counts() below.
                inc = 0
            b["total_qty"] += inc
            b["sheets"].append(dict(pdf=pdf.name, symbol=li.symbol or "",
                                     description=desc[:120]))
        per_file.append(dict(pdf=pdf.name,
                              elapsed_s=round(time.time() - t0, 2),
                              n_legend=len(items),
                              n_tray=n_tray))
        log(f"    legend_rows={len(items):>3}  tray_rows={n_tray:>3}")

    return per_file, list(bucket.values())


def _augment_with_counts(rows: list[dict], log: Logger) -> int:
    """Use equipment_report.json (produced by run_T122_gpk3_count_only.py)
    to fill in per-tray-product symbol counts. We match by (pdf, symbol):
    if the legend row in this sheet had a symbol s, look up that symbol's
    count in equipment_report.json for the same pdf.
    """
    if not EQUIPMENT_JSON.exists():
        log("  WARN: equipment_report.json not found; tray total_qty stays 0")
        return 0
    eq = json.loads(EQUIPMENT_JSON.read_text(encoding="utf-8"))
    by_pdf: dict[str, dict[str, dict]] = {}
    for pf in eq.get("per_file", []):
        by_pdf[pf["pdf"]] = {it["symbol"]: it for it in pf.get("items", [])}

    total_added = 0
    for r in rows:
        for s in r["sheets"]:
            sym = s.get("symbol")
            pdf = s.get("pdf")
            if not sym or pdf not in by_pdf:
                continue
            it = by_pdf[pdf].get(sym)
            if not it:
                continue
            inc = int(it.get("count", 0)) + int(it.get("count_ae", 0))
            r["total_qty"] += inc
            total_added += inc
    return total_added


