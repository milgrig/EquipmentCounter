def write_cables_xlsx(rows: list[dict], path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "cables_by_method"
    headers = ["cable_mark", "cable_color", "laying_method", "cross_section",
               "unit", "total_m"]
    ws.append(headers)
    for r in rows:
        ws.append([r["cable_mark"], r["cable_color"], r["laying_method"],
                   r["cross_section"], r["unit"], r["total_m"]])
    widths = [28, 10, 22, 14, 6, 12]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[chr(ord("A") + i - 1)].width = w
    wb.save(str(path))


def write_trays_xlsx(rows: list[dict], path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "trays"
    headers = ["item_name_normalized", "original_names", "unit",
               "total_qty", "sheets"]
    ws.append(headers)
    for r in rows:
        sheets_str = " | ".join(
            f"{s['pdf']}::{s['symbol']}" for s in r["sheets"][:8]
        )
        ws.append([r["item_name_normalized"],
                   " | ".join(r["original_names"]),
                   r["unit"], r["total_qty"], sheets_str])
    widths = [55, 70, 8, 12, 60]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[chr(ord("A") + i - 1)].width = w
    wb.save(str(path))


